CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name TEXT NOT NULL, username TEXT NOT NULL UNIQUE,
 email TEXT NOT NULL UNIQUE, phone TEXT NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'client' CHECK(role IN ('super_admin','admin','client')),
 profile_picture TEXT DEFAULT '/images/default-avatar.svg', client_tier TEXT NOT NULL DEFAULT 'Regular Client'
 CHECK(client_tier IN ('Premium Client','Standard Client','Regular Client')), account_status TEXT NOT NULL DEFAULT 'active'
 CHECK(account_status IN ('active','inactive')),
 failed_login_attempts INTEGER DEFAULT 0, locked_until TIMESTAMPTZ, admin_approved INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, last_login TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS password_resets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, token_hash TEXT NOT NULL UNIQUE,
 expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS user_sessions (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, session_id TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS activity_logs (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, action TEXT NOT NULL, ip_address TEXT, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS service_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, service TEXT NOT NULL, details TEXT, status TEXT DEFAULT 'pending_review', assigned_to INTEGER,
 admin_note TEXT, reviewed_by INTEGER, reviewed_at TIMESTAMPTZ, estimated_cost TEXT, due_date TIMESTAMPTZ, progress INTEGER NOT NULL DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
 created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(assigned_to) REFERENCES users(id) ON DELETE SET NULL,
 FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
 kind TEXT DEFAULT 'general', is_read INTEGER DEFAULT 0, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS invoices (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id INTEGER NOT NULL, user_id INTEGER NOT NULL, invoice_number TEXT UNIQUE,
 amount TEXT NOT NULL, due_date TIMESTAMPTZ, status TEXT DEFAULT 'draft', notes TEXT, created_by INTEGER NOT NULL,
 created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(request_id) REFERENCES service_requests(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS support_messages (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id INTEGER NOT NULL, sender_id INTEGER NOT NULL,
 body TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(client_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(sender_id) REFERENCES users(id) ON DELETE CASCADE
);
